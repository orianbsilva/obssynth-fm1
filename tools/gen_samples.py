"""The GRAIN oscillator's samples (firmware/src/voice.c), run by tools/build.py and tools/build_sim.sh:

  tools/gen_samples.py OUT.h

Each sample is mono 16-bit at 22.05 kHz (half the rate: the grains are pitched by the note anyway, and the flash is
small), with its root (the MIDI note it sounds: the organ's C4 key sounds C5, a 4' pipe), scaled to one peak. Two come from assets/samples/ (VCSL, CC0: README there), cut and
taken down to 22.05 kHz by a windowed-sinc low-pass; VOX is made here, a voice singing C4 through the vowels A E I O
U (additive: each harmonic at the formants' level). BELL's decay is mostly undone (it would be silent from the middle
on: a grain anywhere in it rings). Each also gets an overview for the screen: OV_W columns of
min / max (int8). Written only when a source or this script is newer than OUT (pure Python: no numpy).
"""
import math
import struct
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
SR = 22050
OV_W = 216
PEAK = 30000
C4 = 261.6256
# name, file (None: made here), seconds kept, root (the MIDI note it sounds)
SAMPLES = [("ORGAN", "vcsl-pipe-organ-quiet-C4.wav", 1.5, 72),
           ("BELL", "vcsl-cowbell.wav", 0.35, 60),
           ("VOX", None, 1.0, 60)]


def read_wav16(path):
    b = path.read_bytes()
    if b[:4] != b"RIFF" or b[8:12] != b"WAVE":
        raise SystemExit(f"{path}: not a WAV")
    pos, fmt, data = 12, None, None
    while pos + 8 <= len(b):
        cid, size = b[pos:pos + 4], struct.unpack("<I", b[pos + 4:pos + 8])[0]
        body = b[pos + 8:pos + 8 + size]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", body[:16])
        elif cid == b"data":
            data = body
        pos += 8 + size + (size & 1)
    if not fmt or fmt[0] != 1 or fmt[1] != 1 or fmt[2] != 44100 or fmt[5] != 16 or data is None:
        raise SystemExit(f"{path}: want 16-bit mono 44.1 kHz, got {fmt}")
    return [v / 32768.0 for v in struct.unpack(f"<{len(data) // 2}h", data)]


def halve(x):
    """44.1 -> 22.05 kHz: a 63-tap windowed-sinc low-pass at 10 kHz, every other sample"""
    taps, fc = 63, 10000.0 / 44100.0
    h = []
    for i in range(taps):
        m = i - (taps - 1) / 2
        s = 2 * fc if m == 0 else math.sin(2 * math.pi * fc * m) / (math.pi * m)
        h.append(s * (0.42 - 0.5 * math.cos(2 * math.pi * i / (taps - 1)) + 0.08 * math.cos(4 * math.pi * i / (taps - 1))))
    g = sum(h)
    h = [v / g for v in h]
    half = (taps - 1) // 2
    out = []
    for n in range(0, len(x), 2):
        acc = 0.0
        for i, c in enumerate(h):
            k = n + i - half
            if 0 <= k < len(x):
                acc += c * x[k]
        out.append(acc)
    return out


def vox(sec):
    """a voice on C4 through A E I O U: harmonics weighted by three formants, a little vibrato"""
    vowels = [(800, 1150, 2900), (400, 1600, 2700), (300, 2300, 3000), (450, 800, 2830), (325, 700, 2530)]
    bw, amp = (80, 90, 120), (1.0, 0.6, 0.3)
    n = int(sec * SR)
    nh = int(9000 / C4)
    ph = [0.0] * (nh + 1)
    out = []
    for t in range(n):
        u = t / n * (len(vowels) - 1)
        i = min(int(u), len(vowels) - 2)
        fr = u - i
        fm = [vowels[i][k] + (vowels[i + 1][k] - vowels[i][k]) * fr for k in range(3)]
        f0 = C4 * (1 + 0.006 * math.sin(2 * math.pi * 5.2 * t / SR))
        s = 0.0
        for h in range(1, nh + 1):
            f = h * f0
            a = sum(amp[k] / (1 + ((f - fm[k]) / bw[k]) ** 2) for k in range(3)) / h ** 0.6
            ph[h] += 2 * math.pi * f / SR
            s += a * math.sin(ph[h])
        out.append(s)
    return out


def flatten(x, amount=0.85):
    """a struck sound held: its decay mostly undone (the level in 10 ms windows, smoothed, divided out to the power
    amount, at most +40 dB), so every POS of the sample rings"""
    w = int(0.01 * SR)
    env = [max(1e-4, math.sqrt(sum(v * v for v in x[i:i + w]) / w)) for i in range(0, len(x), w)]
    sm, out = env[0], []
    for i, v in enumerate(x):
        e = env[min(i // w, len(env) - 1)]
        sm += (e - sm) * 0.002
        out.append(v * min(100.0, (env[0] / max(sm, 1e-4)) ** amount))
    return out


def shape(x, sec):
    """cut to sec, a 10 ms fade in and a 60 ms fade out"""
    x = x[:int(sec * SR)]
    fi, fo = int(0.01 * SR), int(0.06 * SR)
    return [v * min(1.0, i / fi, (len(x) - 1 - i) / fo) for i, v in enumerate(x)]


def main(out):
    out = Path(out)
    srcs = [SRC / "assets" / "samples" / f for _, f, _, _ in SAMPLES if f] + [Path(__file__)]
    if out.exists() and all(out.stat().st_mtime >= s.stat().st_mtime for s in srcs):
        print(f"samples: {out} up to date")
        return
    lines = ["/* generated by tools/gen_samples.py from assets/samples (VCSL, CC0) and VOX made there */",
             "#pragma once", "#include <stdint.h>", f"#define GR_NSMP {len(SAMPLES)}u", f"#define GR_SR {SR}u",
             f"#define GR_OV_W {OV_W}u", ""]
    meta, total = [], 0
    for si, (name, f, sec, root) in enumerate(SAMPLES):
        x = vox(sec) if f is None else halve(read_wav16(SRC / "assets" / "samples" / f))
        if name == "BELL":                               # its ring up: the strike's peak soft-limited (tanh)
            x = flatten(x[:int(sec * SR)])
            rms = math.sqrt(sum(v * v for v in x) / len(x))
            x = [math.tanh(v * 0.3 / rms) for v in x]
        x = shape(x, sec)
        pk = max(abs(v) for v in x) or 1.0
        vals = [max(-32767, min(32767, int(round(v * PEAK / pk)))) for v in x]
        lines.append(f"static const int16_t GR_SMP{si}[{len(vals)}] = {{")
        for i in range(0, len(vals), 16):
            lines.append("    " + ", ".join(map(str, vals[i:i + 16])) + ",")
        lines.append("};")
        mn, mx = [], []
        for c in range(OV_W):
            seg = vals[c * len(vals) // OV_W:max(c * len(vals) // OV_W + 1, (c + 1) * len(vals) // OV_W)]
            mn.append(max(-127, min(seg) * 127 // PEAK))
            mx.append(min(127, max(seg) * 127 // PEAK))
        lines.append(f"static const int8_t GR_OV{si}[2][{OV_W}] = {{{{{', '.join(map(str, mn))}}},")
        lines.append(f"    {{{', '.join(map(str, mx))}}}}};")
        meta.append((name, len(vals), si, root))
        total += len(vals) * 2
        print(f"samples: {name}: {len(vals)} samples, {len(vals) * 2} B")
    lines.append("typedef struct { const char *name; uint32_t n, root; const int16_t *data; const int8_t (*ov)[GR_OV_W]; } "
                 "gr_smp_t;")
    lines.append("static const gr_smp_t GR_SMPS[GR_NSMP] = {")
    for name, n, si, root in meta:
        lines.append(f'    {{"{name}", {n}u, {root}u, GR_SMP{si}, GR_OV{si}}},')
    lines.append("};")
    lines.append("static const char *const GR_NAMES[GR_NSMP] = {" + ", ".join(f'"{m[0]}"' for m in meta) + "};")
    out.write_text("\n".join(lines) + "\n")
    print(f"samples: {out} ({total} B of samples)")


if __name__ == "__main__":
    main(sys.argv[1])
