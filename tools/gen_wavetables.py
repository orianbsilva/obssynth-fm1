"""The WT oscillator's tables (firmware/src/voice.c) from the project's banks (assets/wavetables/*.wav, float32 mono,
1024 samples a wave), run by tools/build.py and tools/build_sim.sh:

  tools/gen_wavetables.py OUT.h

Each wave becomes 10 octave levels, each with only the harmonics that stay under Nyquist over its octave of notes
(level L keeps harmonics below 512 >> L), at WT_LLEN[L] samples (1024 .. 64): the oscillator picks the level from
its increment, so nothing aliases. A bank is scaled to one peak (its waves keep their loudness against each other),
16-bit. Written only when a bank or this script is newer than OUT (a pure-Python FFT: no numpy).
"""
import cmath
import math
import struct
import sys
from pathlib import Path

SRC = Path(__file__).resolve().parents[1]
BANKS = [("BASIC", "bank_basic_8waves_1024samples_32float.wav"),
         ("S>SAW", "bank_sine_to_saw_16waves_1024samples_32float.wav"),
         ("HARM", "bank_harmonic_16waves_1024samples_32float.wav"),
         ("MORPH", "bank_morph_32waves_1024samples_32float.wav")]
N = 1024
LEVELS = 10
LLEN = [1024, 512, 256, 128, 64, 64, 64, 64, 64, 64]
LOFF = [sum(LLEN[:i]) for i in range(LEVELS)]
FRAME = sum(LLEN)                                      # 2304 samples a wave
PEAK = 30000


def read_wav_f32(path):
    b = path.read_bytes()
    if b[:4] != b"RIFF" or b[8:12] != b"WAVE":
        raise SystemExit(f"{path}: not a WAV")
    pos, fmt, data = 12, None, None
    while pos + 8 <= len(b):
        cid, size = b[pos:pos + 4], struct.unpack("<I", b[pos + 4:pos + 8])[0]
        body = b[pos + 8:pos + 8 + size]
        if cid == b"fmt ":
            fmt = struct.unpack("<HHIIHH", body[:16])
        elif cid == b"data":
            data = body
        pos += 8 + size + (size & 1)
    if not fmt or fmt[0] != 3 or fmt[1] != 1 or fmt[5] != 32 or data is None:
        raise SystemExit(f"{path}: want float32 mono, got {fmt}")
    return list(struct.unpack(f"<{len(data) // 4}f", data))


def fft(x, inv=False):
    """iterative radix-2 FFT of a list of complex (len a power of 2)"""
    n = len(x)
    a = list(x)
    j = 0
    for i in range(1, n):                               # bit reversal
        bit = n >> 1
        while j & bit:
            j ^= bit
            bit >>= 1
        j |= bit
        if i < j:
            a[i], a[j] = a[j], a[i]
    size = 2
    sgn = 1 if inv else -1
    while size <= n:
        w = cmath.exp(sgn * 2j * math.pi / size)
        half = size // 2
        for start in range(0, n, size):
            wk = 1
            for k in range(half):
                u, v = a[start + k], a[start + k + half] * wk
                a[start + k], a[start + k + half] = u + v, u - v
                wk *= w
        size *= 2
    if inv:
        a = [v / n for v in a]
    return a


def levels(wave):
    """the wave's 10 band-limited levels, floats, concatenated (FRAME samples)"""
    spec = fft([complex(v) for v in wave])
    out = []
    for lv in range(LEVELS):
        ln, h = LLEN[lv], 512 >> lv
        keep = min(h, ln // 2)                           # harmonics 1 .. keep - 1 (DC dropped too: no offset)
        s = [0j] * ln
        for k in range(1, keep):
            s[k] = spec[k] * ln / N
            s[ln - k] = spec[N - k] * ln / N
        out += [v.real for v in fft(s, inv=True)]
    return out


def main(out):
    out = Path(out)
    srcs = [SRC / "assets" / "wavetables" / f for _, f in BANKS] + [Path(__file__)]
    if out.exists() and all(out.stat().st_mtime >= s.stat().st_mtime for s in srcs):
        print(f"wavetables: {out} up to date")
        return
    lines = ["/* generated by tools/gen_wavetables.py from the banks in assets/wavetables */", "#pragma once",
             "#include <stdint.h>", f"#define WT_NBANK {len(BANKS)}u", f"#define WT_LEVELS {LEVELS}u",
             f"#define WT_FRAME {FRAME}u",
             "static const uint16_t WT_LLEN[WT_LEVELS] = {" + ", ".join(map(str, LLEN)) + "};",
             "static const uint16_t WT_LOFF[WT_LEVELS] = {" + ", ".join(map(str, LOFF)) + "};", ""]
    meta, total = [], 0
    for bi, (name, f) in enumerate(BANKS):
        raw = read_wav_f32(SRC / "assets" / "wavetables" / f)
        if len(raw) % N:
            raise SystemExit(f"{f}: {len(raw)} samples, not waves of {N}")
        frames = [levels(raw[i:i + N]) for i in range(0, len(raw), N)]
        pk = max(abs(v) for fr in frames for v in fr) or 1.0
        vals = [max(-32767, min(32767, int(round(v * PEAK / pk)))) for fr in frames for v in fr]
        lines.append(f"static const int16_t WT_BANK{bi}[{len(vals)}] = {{")
        for i in range(0, len(vals), 16):
            lines.append("    " + ", ".join(map(str, vals[i:i + 16])) + ",")
        lines.append("};")
        meta.append((name, len(frames), bi))
        total += len(vals) * 2
        print(f"wavetables: {name}: {len(frames)} waves, {len(vals) * 2} B")
    lines.append("typedef struct { const char *name; uint32_t n; const int16_t *data; } wt_bank_t;")
    lines.append("static const wt_bank_t WT_BANKS[WT_NBANK] = {")
    for name, n, bi in meta:
        lines.append(f'    {{"{name}", {n}u, WT_BANK{bi}}},')
    lines.append("};")
    lines.append("static const char *const WT_NAMES[WT_NBANK] = {" + ", ".join(f'"{m[0]}"' for m in meta) + "};")
    out.write_text("\n".join(lines) + "\n")
    print(f"wavetables: {out} ({total} B of tables)")


if __name__ == "__main__":
    main(sys.argv[1])
